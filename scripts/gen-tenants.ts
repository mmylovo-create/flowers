// Turns tenants/<slug>/ folders into what the web app needs:
//  - src/generated/tenants.ts   settings bundled into the app (first paint, offline, sample mode)
//  - public/t/<slug>/...        photos, icons and the install manifest of each shop
// Runs automatically before `pnpm dev` and `pnpm build`.
import sharp from 'sharp';
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { listTenants, loadTenant, localMedia, ROOT, tenantDir, tenantStatus } from './lib/tenants.ts';

const PUBLIC_T = join(ROOT, 'public', 't');
const GEN = join(ROOT, 'src', 'generated');

export async function makeIcons(slug: string, logoPath: string | null, name: string, accent: string, bg: string) {
  const out = join(PUBLIC_T, slug);
  mkdirSync(out, { recursive: true });
  let src: Buffer;
  if (logoPath && existsSync(logoPath)) {
    src = readFileSync(logoPath);
  } else {
    const letter = name.trim()[0]?.toUpperCase() ?? '✿';
    src = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512"><rect width="512" height="512" fill="${bg}"/>
      <text x="256" y="330" text-anchor="middle" font-family="Georgia, serif" font-size="240" fill="${accent}">${letter}</text></svg>`);
  }
  const logo = await sharp(src, { density: 300 }).resize(512, 512, { fit: 'contain', background: bg }).png().toBuffer();
  await sharp(logo).resize(192, 192).png().toFile(join(out, 'icon-192.png'));
  await sharp(logo).resize(512, 512).png().toFile(join(out, 'icon-512.png'));
  await sharp(logo).resize(180, 180).flatten({ background: bg }).png().toFile(join(out, 'apple-touch-icon.png'));
  // maskable: keep the logo inside the 80% safe zone
  const inner = await sharp(logo).resize(360, 360, { fit: 'contain', background: bg }).png().toBuffer();
  await sharp({ create: { width: 512, height: 512, channels: 4, background: bg } })
    .composite([{ input: inner, left: 76, top: 76 }]).png().toFile(join(out, 'icon-maskable-512.png'));
  await sharp(logo).resize(48, 48).png().toFile(join(out, 'favicon.png'));
}

export async function genTenants() {
  rmSync(PUBLIC_T, { recursive: true, force: true });
  mkdirSync(GEN, { recursive: true });
  const bundle: Record<string, unknown> = {};
  const problems: string[] = [];
  for (const slug of listTenants()) {
    let t;
    try {
      t = loadTenant(slug);
    } catch (e) {
      problems.push((e as Error).message);
      continue;
    }
    const dir = tenantDir(slug);
    const out = join(PUBLIC_T, slug);
    for (const rel of localMedia(t)) {
      const src = join(dir, rel);
      if (!existsSync(src)) { problems.push(`tenants/${slug}/${rel}: файл не найден`); continue; }
      mkdirSync(dirname(join(out, rel)), { recursive: true });
      copyFileSync(src, join(out, rel));
    }
    const s = t.settings;
    const logo = s.logo && !/^https?:/.test(s.logo) ? join(dir, s.logo) : null;
    await makeIcons(slug, logo, s.name, s.theme.accent, s.theme.background);
    const scope = `/s/${slug}/`;
    writeFileSync(join(out, 'manifest.webmanifest'), JSON.stringify({
      id: scope,
      name: s.name,
      short_name: s.name.slice(0, 12),
      description: s.tagline || s.description.slice(0, 120),
      lang: 'ru',
      start_url: scope,
      scope,
      display: 'standalone',
      orientation: 'portrait',
      background_color: s.theme.background,
      theme_color: s.theme.background,
      icons: [
        { src: `/t/${slug}/icon-192.png`, sizes: '192x192', type: 'image/png', purpose: 'any' },
        { src: `/t/${slug}/icon-512.png`, sizes: '512x512', type: 'image/png', purpose: 'any' },
        { src: `/t/${slug}/icon-maskable-512.png`, sizes: '512x512', type: 'image/png', purpose: 'maskable' },
      ],
      shortcuts: [
        { name: 'Букеты', url: `${scope}bouquets` },
        { name: 'Мои заказы', url: `${scope}orders` },
      ],
    }, null, 2));
    const status = tenantStatus(slug);
    // owner e-mail and Telegram ids stay out of the browser bundle
    bundle[slug] = { slug, settings: t.settings, bouquets: t.bouquets, checked: status.checked };
  }
  const slugs = Object.keys(bundle);
  const def = process.env.VITE_DEFAULT_SHOP && slugs.includes(process.env.VITE_DEFAULT_SHOP)
    ? process.env.VITE_DEFAULT_SHOP
    : (slugs.find((s) => (bundle[s] as { checked: boolean }).checked) ?? slugs[0] ?? '');
  writeFileSync(join(GEN, 'tenants.ts'),
    `// Generated by scripts/gen-tenants.ts from tenants/*/shop.json — do not edit.\n` +
    `import type { BundledTenant } from '../lib/tenantTypes';\n` +
    `export const TENANTS: Record<string, BundledTenant> = ${JSON.stringify(bundle, null, 2)};\n` +
    `export const DEFAULT_SLUG = ${JSON.stringify(def)};\n`);
  return { slugs, problems };
}

if (import.meta.filename === process.argv[1]) {
  const { slugs, problems } = await genTenants();
  console.log(`Shops: ${slugs.join(', ') || '(none)'}`);
  if (problems.length) {
    console.error('Problems:\n' + problems.join('\n'));
    process.exitCode = 1;
  }
}
